/// The name of a symbol table definition: the names of its enclosing modules
/// below the root, then its own name.
///
/// A path without components is the root module, and a path without its last
/// component is the module that encloses it. A definition's path and a
/// reference to one have at least one component.
///
/// Each component is one name, taken as it is: a name that contains `::` is
/// still a single component, so a path built from one qualified name differs
/// from the path that spells the same text as nested modules. Up to two
/// components are stored inline.
#[derive(Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
#[cfg_attr(feature = "salsa", derive(salsa::SalsaValue))]
pub struct SymbolPath(SmallVec<[Symbol; 2]>);

impl SymbolPath {
    /// The separator between components in the textual form.
    pub const SEPARATOR: &'static str = "::";

    /// The path of the root module.
    pub const fn root() -> Self {
        SymbolPath(SmallVec::new_const())
    }

    /// A path from its components, outermost module first. No component
    /// gives the root module.
    pub fn new(components: impl IntoIterator<Item = impl Into<Symbol>>) -> Self {
        SymbolPath(components.into_iter().map(Into::into).collect())
    }

    /// Whether this is the root module.
    pub fn is_root(&self) -> bool {
        self.0.is_empty()
    }

    pub fn components(&self) -> &[Symbol] {
        &self.0
    }

    /// The path's own name, without its modules. The root module has none.
    pub fn leaf(&self) -> Option<&Symbol> {
        self.0.last()
    }

    /// The enclosing modules, outermost first.
    pub fn modules(&self) -> &[Symbol] {
        &self.0[..self.0.len().saturating_sub(1)]
    }

    /// The path of `name` inside this module.
    pub fn child(&self, name: impl Into<Symbol>) -> Self {
        let mut path = self.clone();
        path.push(name);
        path
    }

    /// The enclosing module. The root module has none.
    pub fn parent(&self) -> Option<Self> {
        let (_, modules) = self.0.split_last()?;
        Some(SymbolPath(modules.iter().cloned().collect()))
    }

    /// The path of `name` in the module that encloses this path.
    ///
    /// # Panics
    ///
    /// Panics on the root module, which no module encloses.
    pub fn sibling(&self, name: impl Into<Symbol>) -> Self {
        let mut path = self.clone();
        *path.0.last_mut().expect("the root module has no sibling") = name.into();
        path
    }

    /// Enters `name`, making this the path of `name` inside this module.
    pub fn push(&mut self, name: impl Into<Symbol>) {
        self.0.push(name.into());
    }

    /// Leaves the last component for its enclosing module and returns it.
    pub fn pop(&mut self) -> Option<Symbol> {
        self.0.pop()
    }

    /// The name of a definition directly in the root module.
    pub fn as_simple(&self) -> Option<&Symbol> {
        match self.0.as_slice() {
            [name] => Some(name),
            _ => None,
        }
    }

    /// Whether the path has no enclosing module.
    pub fn is_simple(&self) -> bool {
        self.0.len() == 1
    }

    /// The components joined into one symbol, as [`Display`](std::fmt::Display)
    /// writes them.
    pub fn to_symbol(&self) -> Symbol {
        match self.as_simple() {
            Some(name) => name.clone(),
            None => Symbol::new(&self.to_string()),
        }
    }
}

/// Joins the components with `::`. The result does not tell a component that
/// contains `::` from nested modules; the IR printer writes each component
/// separately.
impl std::fmt::Display for SymbolPath {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        for (index, component) in self.0.iter().enumerate() {
            if index != 0 {
                f.write_str(Self::SEPARATOR)?;
            }
            f.write_str(component.as_str())?;
        }
        Ok(())
    }
}

impl std::fmt::Debug for SymbolPath {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("SymbolPath")?;
        f.debug_list()
            .entries(self.0.iter().map(Symbol::as_str))
            .finish()
    }
}

/// A single name is the path of a definition in the root module.
impl From<Symbol> for SymbolPath {
    fn from(name: Symbol) -> Self {
        SymbolPath(smallvec::smallvec![name])
    }
}

impl From<&Symbol> for SymbolPath {
    fn from(name: &Symbol) -> Self {
        SymbolPath::from(name.clone())
    }
}

impl From<&str> for SymbolPath {
    fn from(name: &str) -> Self {
        SymbolPath::from(Symbol::new(name))
    }
}

impl From<&SymbolPath> for SymbolPath {
    fn from(path: &SymbolPath) -> Self {
        path.clone()
    }
}

/// A path equals a slice or array of the same number of components, each
/// equal to its component, as a `Vec` equals one: `path == ["std", "io",
/// "Io"]` compares text component by component, and `path ==
/// [symbol!("main")]` compares atoms. A `&SymbolPath` compares with a
/// reference through the standard impl for references.
macro_rules! component_eq {
    ($($path:ty => $components:ty),* $(,)?) => {$(
        impl<T, const N: usize> PartialEq<$components> for $path
        where
            Symbol: PartialEq<T>,
        {
            fn eq(&self, other: &$components) -> bool {
                self.0[..] == other[..]
            }
        }
    )*};
}

component_eq! {
    SymbolPath => [T; N],
    SymbolPath => &[T; N],
    &SymbolPath => [T; N],
}

impl<T> PartialEq<[T]> for SymbolPath
where
    Symbol: PartialEq<T>,
{
    fn eq(&self, other: &[T]) -> bool {
        self.0[..] == *other
    }
}

impl<T> PartialEq<&[T]> for SymbolPath
where
    Symbol: PartialEq<T>,
{
    fn eq(&self, other: &&[T]) -> bool {
        self.0[..] == **other
    }
}

impl<T> PartialEq<[T]> for &SymbolPath
where
    Symbol: PartialEq<T>,
{
    fn eq(&self, other: &[T]) -> bool {
        self.0[..] == *other
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Matching a typed operation builds its dialect and operation names, so
    /// those must not reach the dynamic set.
    #[test]
    fn declared_operation_names_are_static() {
        let mut dynamic = Vec::new();
        for crate::op_def::OpDefRegistration(def) in
            inventory::iter::<crate::op_def::OpDefRegistration>
        {
            let schema = &def.schema;
            let attributes = schema.attributes.iter().map(|attribute| attribute.name);
            for name in [schema.dialect, schema.name].into_iter().chain(attributes) {
                if !Symbol::new(name).is_static_or_inline() {
                    dynamic.push(format!("{}.{}: {name}", schema.dialect, schema.name));
                }
            }
        }
        assert!(dynamic.is_empty(), "{dynamic:#?}");
    }

    #[test]
    fn symbol_paths_keep_each_name_as_one_component() {
        let path = SymbolPath::new(["outer", "inner", "same"]);
        assert_eq!(path.components().len(), 3);
        assert_eq!(path.leaf(), Some(&Symbol::new("same")));
        assert_eq!(path.modules(), [Symbol::new("outer"), Symbol::new("inner")]);
        assert_eq!(path.to_string(), "outer::inner::same");
        assert_eq!(path.as_simple(), None);

        // A qualified name is one component, not the modules it spells.
        let flat = SymbolPath::from("outer::inner::same");
        assert!(flat.is_simple());
        assert_eq!(flat.as_simple(), Some(&Symbol::new("outer::inner::same")));
        assert_ne!(flat, path);
        assert_ne!(path, SymbolPath::from("outer::inner::same"));
        assert_eq!(flat.to_symbol(), path.to_symbol());

        let simple = SymbolPath::from("a");
        assert!(simple < SymbolPath::new(["a", "b"]));
        assert_eq!(std::mem::size_of::<SymbolPath>(), 24);
        assert_eq!(std::mem::size_of::<crate::types::Attribute>(), 32);
    }

    #[test]
    fn the_root_module_is_the_path_without_components() {
        let root = SymbolPath::root();
        assert!(root.is_root());
        assert_eq!(root, SymbolPath::new(<[Symbol; 0]>::default()));
        assert_eq!(root.leaf(), None);
        assert!(root.modules().is_empty());
        assert_eq!(root.parent(), None);
        assert_eq!(root.as_simple(), None);
        assert!(!root.is_simple());
        assert_eq!(root.to_string(), "");

        let outer = root.child("outer");
        assert!(root < outer);
        assert_eq!(outer, SymbolPath::from("outer"));
        assert_eq!(outer.parent(), Some(root));
        let same = outer.child("inner").child("same");
        assert_eq!(same, SymbolPath::new(["outer", "inner", "same"]));
        assert_eq!(same.parent(), Some(SymbolPath::new(["outer", "inner"])));
        assert_eq!(
            same.sibling("other"),
            SymbolPath::new(["outer", "inner", "other"])
        );
        assert_eq!(outer.sibling("other"), SymbolPath::from("other"));

        let mut stack = SymbolPath::root();
        stack.push("outer");
        stack.push("inner");
        assert_eq!(stack.child("same"), same);
        assert_eq!(stack.pop(), Some(Symbol::new("inner")));
        assert_eq!(stack, outer);
        assert_eq!(stack.pop(), Some(Symbol::new("outer")));
        assert_eq!(stack.pop(), None);
    }

    #[test]
    fn a_path_equals_an_array_of_its_components() {
        let path = SymbolPath::new(["std", "io", "Io"]);
        assert!(path == ["std", "io", "Io"]);
        assert!(path != ["std::io::Io"]);
        assert!(path != ["std", "io"]);
        assert!(SymbolPath::from("std::io::Io") == ["std::io::Io"]);
        assert!(SymbolPath::from("main") == [crate::symbol!("main")]);
        let root = SymbolPath::root();
        assert!(root == <[&str; 0]>::default());
        let by_ref: &SymbolPath = &path;
        assert!(by_ref == ["std", "io", "Io"]);
        let array = &["std", "io", "Io"];
        assert!(path == array);
        let components: &[&str] = &["std", "io", "Io"];
        assert!(path == *components);
        assert!(path == components);
        assert!(by_ref == components);
        assert!(path != components[..2]);
    }

    #[test]
    #[should_panic(expected = "the root module has no sibling")]
    fn the_root_module_has_no_sibling() {
        SymbolPath::root().sibling("a");
    }

    #[test]
    fn escaped_literal_symbols_match_runtime_names() {
        const QUOTED: Symbol = crate::symbol!("quoted\"symbol");
        let unicode = Symbol::new("escaped_\u{1f980}");
        assert_eq!(QUOTED.as_str(), "quoted\"symbol");
        assert_eq!(unicode.as_str(), "escaped_🦀");
        assert!(QUOTED.is_static_or_inline());
        assert!(unicode.is_static_or_inline());
    }

    #[test]
    fn symbols_compare_and_order_by_text() {
        let short = Symbol::new("short");
        let text = String::from("a_name_longer_than_seven_bytes");
        let long = Symbol::new(&text);
        assert_eq!(long, Symbol::new(&text));
        assert_eq!(long, "a_name_longer_than_seven_bytes");
        assert!(long < short);
        assert!(short.is_static_or_inline());
        assert!(!long.is_static_or_inline());
    }
}

