//! Tribute TrunkIR crate.
//!
//! `new-plans/ir.md` defines TrunkIR as the compiler's central multi-level dialect IR.
//! This crate provides IR definitions for the multi-level dialect system.

#![recursion_limit = "512"]

// Self-alias so proc-macro–generated `::trunk_ir::...` paths resolve
// inside this crate the same way they do for downstream consumers.
extern crate self as trunk_ir;

// === Salsa-independent primitives ===
pub mod symbol;
pub mod symbol_table;

// === Diagnostic types ===
pub mod diagnostic;

// === Source location types ===
pub mod location;

// === Operation interface (purity, isolation) ===
pub mod op_interface;

// === Textual assembly format hooks ===
pub mod asm_format;
pub mod attr_kind;

// === Operation and type utilities ===
pub mod name;
pub mod op_def;
pub mod op_flag;
pub mod op_schema;
pub mod ops;
pub mod type_constraint;
pub mod type_def;
pub mod type_verifier;

// === IR core structures ===
pub mod callable;
pub mod context;
pub mod dominance;
pub mod refs;
pub mod types;

// === Dialect definitions ===
pub mod dialect;

// === IR mapping for clone/transform ===
pub mod ir_mapping;

// === IR infrastructure ===
pub mod analysis;
pub mod pass;
pub mod printer;
pub mod rewrite;
pub mod transforms;
pub mod validation;
pub mod walk;

// === Dialect conversion utilities ===
pub mod conversion;

// === IR text format parser ===
pub mod parser;

// === Random IR for property tests ===
#[cfg(test)]
mod prop;

// Re-export proc macro for dialect definitions
pub use trunk_ir_macros::dialect;

// Re-export proc macros for interface and flag declarations.
pub use trunk_ir_macros::{op_flag, op_interface, type_interface};

// Re-export `inventory` so the proc-macro–generated submit blocks
// resolve `::trunk_ir::inventory::submit!` without requiring consumer
// crates to declare a direct `inventory` dependency.
#[doc(hidden)]
pub use inventory;

/// Support for code generated by trunk-ir's proc macros.
#[doc(hidden)]
pub mod __private {
    pub use inventory;
    pub use rustc_hash::FxHashMap as HashMap;
}

// Re-export smallvec for use in macros and external crates
pub use smallvec;

pub use location::{Span, Spanned};
pub use op_def::{OpDef, OpName, OpNameArg};
pub use ops::ConversionError;
pub use symbol::{BlockId, IdVec, Symbol, SymbolPath, SymbolVec};

pub use smallvec::smallvec as idvec;

// Re-exports from submodules (previously from arena/mod.rs)
pub use context::{
    BlockArgData, BlockData, BlockList, IrContext, OpList, OperationData, OperationDataBuilder,
    RegionData, RegionList, Regions, Successors, Use, ValueData,
};
pub use ir_mapping::IrMapping;
pub use refs::{BlockRef, OpRef, PathRef, RegionRef, TypeRef, ValueDef, ValueRef};
pub use rewrite::Module;
pub use type_def::{TypeDef, TypeName, TypeNameArg};
pub use types::{
    Attribute, AttributeIntoIter, AttributeIter, AttributeIterMut, AttributeKey, AttributeKeys,
    AttributeMap, AttributeValues, AttributeValuesMut, AttributeView, AttributeViewMut,
    IntegerOutOfRange, Location, PathInterner, StringArg, StringPool, StringRef, TypeData,
    TypeDataBuilder, TypeInterner,
};
pub use walk::WalkAction;
